"""Base tool definition and path safety validation."""

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any
from pydantic import BaseModel


def validate_path_safety(file_path: str, project_root: Path) -> Path:
    """Validate that file_path resolves within project_root.

    Raises ValueError if path attempts traversal outside project_root.
    """
    root_resolved = project_root.resolve()

    # Handle absolute vs relative path inputs
    target_path = Path(file_path)
    if not target_path.is_absolute():
        target_path = root_resolved / target_path

    try:
        resolved = target_path.resolve()
    except Exception as e:
        raise ValueError(f"Invalid path '{file_path}': {e}")

    if not resolved.is_relative_to(root_resolved):
        raise ValueError(
            f"Path traversal rejected: '{file_path}' resolves outside project root '{root_resolved}'."
        )

    return resolved


class BaseTool(ABC):
    """Abstract Base Class for all tools."""

    name: str
    description: str
    input_schema: type[BaseModel]

    def __init__(self, project_root: Path) -> None:
        self.project_root = project_root.resolve()

    def get_anthropic_schema(self) -> dict[str, Any]:
        """Generate schema formatted for Anthropic API tool definition."""
        schema = self.input_schema.model_json_schema()
        # Remove titles generated by Pydantic for clean Anthropic schemas
        schema.pop("title", None)
        return {
            "name": self.name,
            "description": self.description,
            "input_schema": schema,
        }

    @abstractmethod
    def execute(self, **kwargs: Any) -> str:
        """Execute the tool with validated kwargs and return string output."""
        pass
